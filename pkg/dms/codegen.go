func exportName(raw string) string {
	parts := identifierParts(raw)
	if len(parts) == 0 {
		return ""
	}
	var b strings.Builder
	for _, part := range parts {
		upper := strings.ToUpper(part)
		if isCommonInitialism(upper) {
			b.WriteString(upper)
			continue
		}
		runes := []rune(part)
		if len(runes) == 0 {
			continue
		}
		b.WriteRune(unicode.ToUpper(runes[0]))
		for _, r := range runes[1:] {
			b.WriteRune(r)
		}
	}
	out := b.String()
	if out == "" || !isGoIdentifier(out) || !unicode.IsLetter([]rune(out)[0]) {
		return ""
	}
	return out
}

func snakeIdentifier(raw string) string {
	parts := identifierParts(raw)
	if len(parts) == 0 {
		return "field"
	}
	for i := range parts {
		parts[i] = strings.ToLower(parts[i])
	}
	out := strings.Join(parts, "_")
	if out == "" || !isPyIdentifier(out) || isPyKeyword(out) {
		out = "field_" + out
	}
	return out
}

func identifierParts(raw string) []string {
	var parts []string
	var current []rune
	flush := func() {
		if len(current) > 0 {
			parts = append(parts, string(current))
			current = nil
		}
	}
	var prev rune
	for i, r := range raw {
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			if i > 0 && unicode.IsUpper(r) && prev != 0 && (unicode.IsLower(prev) || unicode.IsDigit(prev)) {
				flush()
			}
			current = append(current, r)
			prev = r
			continue
		}
		flush()
		prev = 0
	}
	flush()
	return parts
}

func uniqueGoFieldName(base string, seen map[string]int) string {
	if base == "" {
		base = "Field"
	}
	if !isGoIdentifier(base) || !unicode.IsLetter([]rune(base)[0]) {
		base = "Field" + base
	}
	count := seen[base]
	seen[base] = count + 1
	if count == 0 {
		return base
	}
	return fmt.Sprintf("%s%d", base, count+1)
}

