#!/usr/bin/env python3
"""Check that published Python snippets can stand on their own.

The troubleshooting guides are copied into consumer projects and read on their
own, so a snippet that calls `boto3.client(...)` without importing `boto3` is a
drift defect: it works only if a neighbouring example happens to import it. This
check parses every ```python block in the hand-written guides and fails when a
block uses a module it does not import itself.

It is deliberately offline: parsing and AST inspection only, no execution, no
network, no AWS client construction.
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]

# The hand-written guides that publish Python snippets. The site copies under
# docs/runtimes/ are generated by `make sync-runtime-docs-site` from the py/docs
# originals, so checking both proves the copy did not drift.
GUIDES = [
    "docs/troubleshooting.md",
    "docs/runtimes/python.md",
    "py/docs/troubleshooting.md",
    "docs/runtimes/python/troubleshooting.md",
]

# Modules a snippet must import itself before it can use them.
GUARDED_MODULES = ("boto3", "tabletheory_py")


def python_blocks(path: Path) -> list[tuple[int, str]]:
    lines = path.read_text(encoding="utf-8").splitlines()
    blocks: list[tuple[int, str]] = []
    start: int | None = None
    body: list[str] = []
    for index, line in enumerate(lines, start=1):
        stripped = line.strip()
        if start is None and stripped in ("```python", "```py"):
            start = index + 1
            body = []
            continue
        if start is not None and stripped == "```":
            blocks.append((start, "\n".join(body)))
            start = None
            continue
        if start is not None:
            body.append(line)
    return blocks


def imported_names(tree: ast.AST) -> set[str]:
    names: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            names.update(alias.name.split(".")[0] for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module:
            names.add(node.module.split(".")[0])
    return names


def used_modules(tree: ast.AST) -> set[str]:
    used: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name):
            used.add(node.value.id)
    return used


def check_guide(path: Path, problems: list[str]) -> int:
    blocks = python_blocks(path)
    for line, source in blocks:
        # A guide may show a fragment that continues an earlier block, such as an
        # `except` clause. Give it a syntactic home so the parse check measures
        # syntax rather than whether the snippet is complete on its own.
        first = next((row for row in source.splitlines() if row.strip()), "")
        probe = f"try:\n    pass\n{source}" if first.strip().startswith(("except", "elif", "else")) else source
        try:
            tree = ast.parse(probe)
        except SyntaxError as err:
            problems.append(f"{path}:{line}: snippet does not parse: {err.msg}")
            continue

        imported = imported_names(tree)
        for module in GUARDED_MODULES:
            if module in used_modules(tree) and module not in imported:
                problems.append(
                    f"{path}:{line}: snippet uses {module} without importing it"
                )
    return len(blocks)


def main() -> int:
    problems: list[str] = []
    total = 0
    for rel_path in GUIDES:
        path = REPO_ROOT / rel_path
        if not path.is_file():
            problems.append(f"missing guide: {rel_path}")
            continue
        total += check_guide(path, problems)

    if problems:
        print("doc-snippets: FAIL", file=sys.stderr)
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        return 1

    print(f"doc-snippets: PASS (blocks={total})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
